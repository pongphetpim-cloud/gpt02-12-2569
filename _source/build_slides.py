S = []  # (html)


def notes_attr(n):
    return escape(n, quote=True)


def slide(inner, notes="", cls="", mode="both", mins=None, sect_min=None):
    a = f' data-mode="{mode}" data-notes="{notes_attr(notes)}"'
    if mins: a += f' data-min="{mins}"'
    if sect_min: a += f' data-sect-min="{sect_min}"'
    S.append(f'<section class="slide {cls}"{a}>\n{inner}\n</section>')


def pre(pid, size=""):
    return f'<pre class="{size}" data-pid="{pid}">{escape(P[pid])}</pre>'


def chips(*cs):
    return "".join(f'<span class="chip {c}">{t}</span>' for c, t in cs)


def eyebrow(cs, right=""):
    return f'<div class="eyebrow">{chips(*cs)}<span class="mins">{right}</span></div>'


def steps(title, items):
    return f'<div class="steps"><b>{title}</b><ol>' + "".join(f"<li>{i}</li>" for i in items) + "</ol></div>"


def watch(title, text):
    return f'<div class="watch"><b>{title}</b><p>{text}</p></div>'


def timer(m):
    return f'<div class="timer"><span class="t">{m}:00</span><span class="lbl">เหลือเวลา</span></div>'


def board(cs, right, h2, left_html, side_html, notes, mins=None, mode="both"):
    head = f"<h2 class='bh'>{h2}</h2>" if h2 else ""
    slide(f"""{eyebrow(cs, right)}{head}
<div class="board"><div class="left">{left_html}</div><div class="side">{side_html}{timer(mins) if mins else ''}</div></div>""",
          notes, mode=mode, mins=mins)


def sect(chip, title, sub, num, notes, tool="", mode="both", sect_min=None):
    slide(f"""<div class="sectchips"><span class="chip">{chip}</span>{f'<span class="chip {tool[0]}">{tool[1]}</span>' if tool else ''}</div>
<h1>{title}</h1><p>{sub}</p><div class="num">{num}</div>""", notes, cls="sect", mode=mode, sect_min=sect_min)


